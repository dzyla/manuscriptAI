const load = (name: string): ArrayBuffer => {
  const b = readFileSync(new URL(`../../test/fixtures/docx/${name}`, import.meta.url));
  return b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength) as ArrayBuffer;
};

async function readData(data: ArrayBuffer, opts: OpenOptions = {}) {
  const pkg = await openPackage(data, opts);
  const report = createReport();
  let n = 0;
  const ctx: ReadContext = {
    pkg,
    styles: readStyles(pkg, report),
    report,
    preservation: emptyPreservationStore(),
    assets: [],
    nextId: () => `b${++n}`,
  };
  const body = pkg.xml(mainDocumentPart(pkg))!.getElementsByTagNameNS(W_NS, 'body')[0];
  const result = await readBody(body, ctx);
  return { pkg, ctx, report, body, ...result, doc: { type: 'doc', content: result.blocks } as JSONContent };
}

const textOf = (n: JSONContent): string => (n.type === 'text' ? n.text ?? '' : (n.content ?? []).map(textOf).join(''));
const walk = (n: JSONContent, fn: (x: JSONContent) => void): void => {
  fn(n);
  (n.content ?? []).forEach(c => walk(c, fn));
};
const all = (blocks: JSONContent[], pred: (n: JSONContent) => boolean): JSONContent[] => {
  const out: JSONContent[] = [];
  blocks.forEach(b => walk(b, n => pred(n) && out.push(n)));
  return out;
};
const images = (blocks: JSONContent[]): JSONContent[] => all(blocks, n => n.type === 'resizableImage');
const blockIdOf = (n: JSONContent): string => (n.attrs!.ooxml as { blockId: string }).blockId;
const indexOfText = (blocks: JSONContent[], text: string): number => blocks.findIndex(b => b.type === 'paragraph' && textOf(b) === text);
const sha256 = (data: ArrayBuffer): string => createHash('sha256').update(new Uint8Array(data)).digest('hex');
const bytesEqual = (a: ArrayBuffer, b: Uint8Array): boolean => Buffer.compare(Buffer.from(a), Buffer.from(b)) === 0;

