describe('captions', () => {
  const img = (anchorBlockId?: string): JSONContent => ({ type: 'resizableImage', attrs: { assetId: 'a', ...(anchorBlockId ? { anchorBlockId } : {}) } });
  const para = (text: string, styleId: string | null = null): JSONContent => ({ type: 'paragraph', attrs: { styleId }, content: [{ type: 'text', text }] });

  it('a figure with no caption, and a caption with no figure, are both fine', () => {
    expect(matchCaptions([para('Fig. 9. Orphan caption.'), img(), para('Plain text after.')])).toEqual([{ image: 1, caption: null, how: null }]);
  });

  it('an unstyled "Fig. N." paragraph is a caption (the real documents never use the Caption style); "Figure 3 shows" is not', () => {
    expect(matchCaptions([img(), para('Fig. 1. Something.')])).toEqual([{ image: 0, caption: 1, how: 'label' }]);
    expect(matchCaptions([img(), para('Figure 2: Something.')])).toEqual([{ image: 0, caption: 1, how: 'label' }]);
    expect(matchCaptions([img(), para('Fig.1. Tight.')])).toEqual([{ image: 0, caption: 1, how: 'label' }]);
    expect(matchCaptions([img(), para('Figure 3 shows that the effect is large.')])).toEqual([{ image: 0, caption: null, how: null }]);
  });

  it('a Caption-styled paragraph wins, and each caption is used once, in order', () => {
    expect(matchCaptions([img(), para('Whatever it says', 'caption')])).toEqual([{ image: 0, caption: 1, how: 'style' }]);
    expect(matchCaptions([img(), img(), para('Fig. 1. a'), para('Fig. 2. b')])).toEqual([
      { image: 0, caption: null, how: null }, // the next figure is reached first: a caption is never taken from beyond it
      { image: 1, caption: 2, how: 'label' },
    ]);
  });

  it('a picture lifted out of a paragraph of text reaches the caption written after that paragraph, and does not cross the next figure', () => {
    expect(matchCaptions([img('h'), para('Body text beside the figure.'), para('Fig. 4. The legend.')])).toEqual([{ image: 0, caption: 2, how: 'label' }]);
    expect(matchCaptions([img('h'), img('h'), para('Body.'), para('Fig. 5. A.'), para('Fig. 6. B.')])).toEqual([
      { image: 0, caption: 3, how: 'label' },
      { image: 1, caption: 4, how: 'label' },
    ]);
    expect(matchCaptions([img(), para('x'), para('y'), para('z'), para('Fig. 7. too far.')])).toEqual([{ image: 0, caption: null, how: null }]);
  });

  it('"Figure " followed by a SEQ field is a caption too (the number is in the field, not in the text)', () => {
    const seq: JSONContent = { type: 'paragraph', attrs: {}, content: [{ type: 'text', text: 'Figure ' }, { type: 'opaqueInline', attrs: { label: 'field' } }, { type: 'text', text: '. Text' }] };
    expect(matchCaptions([img(), seq])).toEqual([{ image: 0, caption: 1, how: 'label' }]);
  });

  it('an image with no caption in the document reads', async () => {
    const r = await readData(await build({ body: figure('rId10') + p('Ordinary text.'), ...STD }));
    expect(r.figures).toEqual([{ image: 0, caption: null, how: null }]);
  });
});

