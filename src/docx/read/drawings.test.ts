// ─── captions ───────────────────────────────────────────────────────────────────────────────────────────────────

describe('captions', () => {
  const img = (anchorBlockId?: string): JSONContent => ({ type: 'resizableImage', attrs: { assetId: 'a', ...(anchorBlockId ? { anchorBlockId } : {}) } });
  const para = (text: string, styleId: string | null = null): JSONContent => ({ type: 'paragraph', attrs: { styleId }, content: [{ type: 'text', text }] });
  const pairs = (blocks: JSONContent[]) => matchCaptions(blocks).map(m => [m.image, m.caption, m.how]);

  it('a figure with no caption, and a caption with no figure, are both fine', () => {
    expect(pairs([para('Fig. 9. Orphan caption.'), img(), para('Plain text after.')])).toEqual([[1, null, null]]);
  });

  it('an unstyled "Fig. N." paragraph is a caption (the real documents never use the Caption style)', () => {
    expect(pairs([img(), para('Fig. 1. Something.')])).toEqual([[0, 1, 'label']]);
    expect(pairs([img(), para('Figure 1: Something.')])).toEqual([[0, 1, 'label']]);
    expect(pairs([img(), para('Fig.1. Tight.')])).toEqual([[0, 1, 'label']]);
  });

  it('plain prose that starts with a figure reference is not a caption', () => {
    expect(pairs([img(), para('Figure 1 shows that the effect is large.')])).toEqual([[0, null, null]]);
    expect(pairs([img(), para('Figures are described below.')])).toEqual([[0, null, null]]);
  });

  it('every separator after the number, a panel letter, "figs", and the extended-data and supplementary prefixes are recognised', () => {
    for (const text of ['Fig. 1| Text', 'Fig. 1 | Text', 'Fig. 1\u2013 Text', 'Fig. 1\u2014 Text', 'Fig. 1- Text', 'Fig. 1: Text', 'Fig. 1A. Text', 'Figs. 1. Text', 'Extended Data Fig. 1. Text', 'Supplementary Figure S1. Text', 'FIGURE 1. Text']) {
      expect(pairs([img(), para(text)]), text).toEqual([[0, 1, 'label']]);
    }
    expect(pairs([img(), para('Fig. 1, Text')]), 'a comma is not a caption delimiter').toEqual([[0, null, null]]);
  });

  it('a Caption-styled paragraph is a caption even when its text says nothing about a figure', () => {
    expect(pairs([img(), para('Whatever it says', 'caption')])).toEqual([[0, 1, 'style']]);
  });

  it('the NEAREST caption of either kind is taken: a label paragraph in front of a styled one wins, and the reverse', () => {
    expect(pairs([img(), para('Fig. 1. Label first.'), para('Styled second', 'caption')])).toEqual([[0, 1, 'label']]);
    expect(pairs([img(), para('Styled first', 'caption'), para('Fig. 1. Label second.')])).toEqual([[0, 1, 'style']]);
  });

  it('a caption is never taken from beyond the next figure, and is used once', () => {
    expect(pairs([img(), img(), para('Fig. 1. a'), para('Fig. 2. b')])).toEqual([[0, null, null], [1, 2, 'label']]);
  });

  it('the label number is checked against the order of the figures: another figure\'s caption is not taken', () => {
    // fig 1 must not take the caption of fig 2, which sits between the two figures (a caption written BEFORE its figure is not supported)
    expect(pairs([img(), para('Fig. 2. Belongs to the next figure.'), img()])).toEqual([[0, null, null], [2, null, null]]);
    // in order: 1, 2, 3
    expect(pairs([img(), para('Fig. 1. a'), img(), para('Fig. 2. b'), img(), para('Fig. 3. c')])).toEqual([[0, 1, 'label'], [2, 3, 'label'], [4, 5, 'label']]);
    // a figure number that skips ahead is not the next one
    expect(pairs([img(), para('Fig. 1. a'), img(), para('Fig. 4. d')])).toEqual([[0, 1, 'label'], [2, null, null]]);
    // numbering that restarts at 1 (a grant whose sections each number their figures) is fine
    expect(pairs([img(), para('Fig. 1. a'), img(), para('Fig. 2. b'), img(), para('Fig. 1. again')])).toEqual([[0, 1, 'label'], [2, 3, 'label'], [4, 5, 'label']]);
    // supplementary figures are a series of their own
    expect(pairs([img(), para('Fig. 1. a'), img(), para('Supplementary Fig. S1. s'), img(), para('Fig. 2. b')])).toEqual([[0, 1, 'label'], [2, 3, 'label'], [4, 5, 'label']]);
    // a rejected candidate does not stop a later one in reach from being taken
    expect(pairs([img(), para('Fig. 7. Another figure.'), para('Styled', 'caption')])).toEqual([[0, 2, 'style']]);
  });

  const chart = (label = 'chart'): JSONContent => ({ type: 'paragraph', attrs: {}, content: [{ type: 'opaqueInline', attrs: { label } }] });

  it('a skipped number is trusted when an opaque drawing between the figures explains it (a chart is an atom, not an image)', () => {
    expect(pairs([img(), para('Fig. 1. a'), chart(), img(), para('Fig. 3. c'), img(), para('Fig. 4. d')])).toEqual([[0, 1, 'label'], [3, 4, 'label'], [5, 6, 'label']]);
    for (const label of ['drawing', 'chart', 'SmartArt', 'text box', 'shape', 'picture', 'embedded object']) {
      expect(pairs([img(), para('Fig. 1. a'), chart(label), img(), para('Fig. 3. c')]), label).toEqual([[0, 1, 'label'], [3, 4, 'label']]);
    }
    expect(pairs([img(), para('Fig. 1. a'), chart('field'), img(), para('Fig. 3. c')]), 'a field is not a drawing').toEqual([[0, 1, 'label'], [3, null, null]]);
  });

  it('each skipped number needs a drawing of its own', () => {
    expect(pairs([img(), para('Fig. 1. a'), chart(), img(), para('Fig. 4. d')])).toEqual([[0, 1, 'label'], [3, null, null]]);
    expect(pairs([img(), para('Fig. 1. a'), chart(), chart(), img(), para('Fig. 4. d')])).toEqual([[0, 1, 'label'], [4, 5, 'label']]);
  });

  it('an UNEXPLAINED gap is not trusted, and the captions after it that depend on it are lost with it (a known cost)', () => {
    expect(pairs([img(), para('Fig. 1. a'), img(), para('Fig. 3. c'), img(), para('Fig. 4. d')])).toEqual([[0, 1, 'label'], [2, null, null], [4, null, null]]);
    // a figure that does not start at 1 (an excerpt) is not trusted either, unless drawings before it explain it
    expect(pairs([img(), para('Fig. 3. c')])).toEqual([[0, null, null]]);
    expect(pairs([chart(), chart(), img(), para('Fig. 3. c')])).toEqual([[2, 3, 'label']]);
  });

  it('a repeated or backwards number is refused, even when drawings are around to explain a gap', () => {
    expect(pairs([img(), para('Fig. 2. a'), img(), para('Fig. 2. again')])).toEqual([[0, null, null], [2, null, null]]);
    expect(pairs([img(), para('Fig. 1. a'), chart(), img(), para('Fig. 3. b'), img(), para('Fig. 2. back')])).toEqual([[0, 1, 'label'], [3, 4, 'label'], [5, null, null]]);
    expect(pairs([img(), para('Fig. 1. a'), chart(), chart(), img(), para('Fig. 3. b'), img(), para('Fig. 3. same again')])).toEqual([[0, 1, 'label'], [4, 5, 'label'], [6, null, null]]);
    expect(pairs([chart(), chart(), chart(), img(), para('Fig. 3. c'), img(), para('Fig. 2. back')])).toEqual([[3, 4, 'label'], [5, null, null]]);
  });

  it('a drawing only explains the gap between ITS neighbours, and only once', () => {
    expect(pairs([chart(), img(), para('Fig. 1. a'), img(), para('Fig. 3. c')])).toEqual([[1, 2, 'label'], [3, null, null]]);
  });

  it('supplementary series, "Supplementary Figure 1", restarts at 1 and panels (1A, 1B) still pair', () => {
    expect(pairs([img(), para('Fig. 1. a'), img(), para('Supplementary Fig. S1. s'), img(), para('Supplementary Figure 2. t'), img(), para('Fig. 2. b')])).toEqual([[0, 1, 'label'], [2, 3, 'label'], [4, 5, 'label'], [6, 7, 'label']]);
    expect(pairs([img(), para('Fig. 1A. a'), img(), para('Fig. 1B. b'), img(), para('Fig. 2. c'), img(), para('Fig. 1. restart')])).toEqual([[0, 1, 'label'], [2, 3, 'label'], [4, 5, 'label'], [6, 7, 'label']]);
  });

  it('end to end: one chart among the figures costs no later caption', async () => {
    const chartPara = `<w:p><w:r><w:drawing><wp:inline xmlns:wp="${WPNS}"><wp:extent cx="100" cy="100"/><wp:docPr id="9" name="z"/><a:graphic xmlns:a="${ANS}"><a:graphicData uri="http://schemas.openxmlformats.org/drawingml/2006/chart"/></a:graphic></wp:inline></w:drawing></w:r></w:p>`;
    const body = figure('rId10') + p('Fig. 1. a') + chartPara + p('Fig. 2. the chart') + figure('rId11') + p('Fig. 3. c');
    const r = await readData(await build({ body, ...STD }));
    expect(r.figures.map(f => [f.image, f.caption])).toEqual([[0, 1], [4, 5]]);
  });

  it('a picture lifted out of a paragraph of text reaches the caption written after that paragraph, and does not cross the next figure', () => {
    expect(pairs([img('h'), para('Body text beside the figure.'), para('Fig. 1. The legend.')])).toEqual([[0, 2, 'label']]);
    expect(pairs([img('h'), img('h'), para('Body.'), para('Fig. 1. A.'), para('Fig. 2. B.')])).toEqual([[0, 3, 'label'], [1, 4, 'label']]);
    expect(pairs([img(), para('x'), para('y'), para('z'), para('Fig. 1. too far.')])).toEqual([[0, null, null]]);
  });

  it('"Figure " followed by a SEQ field is a caption too (the number is in the field, not in the text)', () => {
    const seq: JSONContent = { type: 'paragraph', attrs: {}, content: [{ type: 'text', text: 'Figure ' }, { type: 'opaqueInline', attrs: { label: 'field' } }, { type: 'text', text: '. Text' }] };
    expect(pairs([img(), seq])).toEqual([[0, 1, 'label']]);
  });

  it('a comment anchor or bookmark in front of the label is not part of it', () => {
    const marked = (label: string): JSONContent => ({ type: 'paragraph', attrs: {}, content: [{ type: 'opaqueInline', attrs: { label } }, { type: 'text', text: 'Fig. 1. Text' }] });
    expect(pairs([img(), marked('comment anchor')])).toEqual([[0, 1, 'label']]);
    expect(pairs([img(), marked('bookmark')])).toEqual([[0, 1, 'label']]);
    expect(pairs([img(), marked('field start')])).toEqual([[0, null, null]]);
  });

  it('an image with no caption in the document reads', async () => {
    const r = await readData(await build({ body: figure('rId10') + p('Ordinary text.'), ...STD }));
    expect(r.figures).toEqual([{ image: 0, caption: null, how: null }]);
  });
});

