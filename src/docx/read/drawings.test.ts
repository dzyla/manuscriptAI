interface Pkg {
  body: string;
  media?: Record<string, Uint8Array>;
  /** Extra `<Relationship>` elements. */
  rels?: string;
  numbering?: string;
}
async function build({ body, media = {}, rels = '', numbering = NUMBERING }: Pkg): Promise<ArrayBuffer> {
  const zip = new JSZip();
  const ct = 'application/vnd.openxmlformats-officedocument.wordprocessingml';
  zip.file('[Content_Types].xml', `<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Default Extension="png" ContentType="image/png"/><Default Extension="svg" ContentType="image/svg+xml"/><Override PartName="/word/document.xml" ContentType="${ct}.document.main+xml"/><Override PartName="/word/styles.xml" ContentType="${ct}.styles+xml"/><Override PartName="/word/numbering.xml" ContentType="${ct}.numbering+xml"/></Types>`);
  zip.file('_rels/.rels', `<?xml version="1.0"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="${RNS}/officeDocument" Target="word/document.xml"/></Relationships>`);
  zip.file('word/_rels/document.xml.rels', `<?xml version="1.0"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="${RNS}/styles" Target="styles.xml"/><Relationship Id="rId2" Type="${RNS}/numbering" Target="numbering.xml"/>${rels}</Relationships>`);
  zip.file('word/document.xml', `<?xml version="1.0"?><w:document xmlns:w="${WNS}" xmlns:r="${RNS}"><w:body>${body}<w:sectPr><w:pgSz w:w="12240" w:h="15840"/><w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440"/></w:sectPr></w:body></w:document>`);
  zip.file('word/styles.xml', STYLES);
  zip.file('word/numbering.xml', numbering);
  for (const [name, bytes] of Object.entries(media)) zip.file(`word/media/${name}`, bytes);
  return zip.generateAsync({ type: 'arraybuffer' });
}
