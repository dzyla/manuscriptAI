describe('body assembly', () => {
  it('inferHeadings receives the grouped document (lifted pictures, lists and tables included): its indices are positions in it', async () => {
    const bold = '<w:b/>';
    const body =
      `<w:p>${anchorPic('rId10')}<w:r><w:t>Text the picture floats beside.</w:t></w:r></w:p>` +
      p('Specific Aims', '', bold) +
      p('A paragraph of ordinary running text that is long enough to be plainly body text and not a title at all, so that the detector has something to compare.') +
      tbl(p('cell')) +
      li('item') +
      p('Significance', '', bold) +
      p('More ordinary running text that goes on for a while so that the heading above it is followed by real prose, as it would be in a grant.');
    const r = await readData(await build({ body, ...STD }));
    expect(r.blocks.map(b => b.type).slice(0, 4)).toEqual(['resizableImage', 'paragraph', 'paragraph', 'paragraph']);
    const found = inferHeadings(r.doc, r.ctx);
    expect(found.map(c => c.text)).toEqual(['Specific Aims', 'Significance']);
    for (const c of found) expect(textOf(r.blocks[c.index])).toBe(c.text); // the index is a position in the grouped array
    const applied = applyHeadings(r.doc, found);
    expect(applied.content!.filter(b => b.type === 'heading').map(textOf)).toEqual(['Specific Aims', 'Significance']);
    expect(applied.content!.filter(b => b.type === 'heading').every(isBlockUntouched)).toBe(false); // converted: no longer the paragraph it was
    expect(applied.content!.filter(b => b.type === 'heading').every(b => !!b.attrs!.ooxml)).toBe(true); // but provenance is kept
    expect(applied.content!.filter(b => b.type === 'resizableImage' || b.type === 'table')).toHaveLength(2);
  });

  it('a title followed by a picture is still a title: a figure on its own line, or a picture lifted out of the next paragraph, is not "something in between"', async () => {
    const bold = '<w:b/>';
    const body =
      p('Cell culture conditions', '', bold) +
      `<w:p>${anchorPic('rId10')}<w:r><w:t>The cells were grown in a standard medium at thirty seven degrees for two days before they were fixed.</w:t></w:r></w:p>` +
      p('Imaging schedule', '', bold) +
      figure('rId11') +
      p('Fig. 1. The imaging schedule.');
    const r = await readData(await build({ body, ...STD }));
    expect(r.blocks.map(b => b.type)).toEqual(['paragraph', 'resizableImage', 'paragraph', 'paragraph', 'resizableImage', 'paragraph']);
    const found = inferHeadings(r.doc, r.ctx);
    expect(found.map(c => c.text)).toEqual(['Cell culture conditions', 'Imaging schedule']);
    expect(found.map(c => c.index)).toEqual([0, 3]);
    expect(found[1].evidence.some(e => /followed by a figure/.test(e))).toBe(true);
    // a title followed by a TABLE is still not a title (unchanged)
    const tableCase = await readData(await build({ body: p('Imaging schedule', '', bold) + tbl(p('cell')), ...STD }));
    expect(inferHeadings(tableCase.doc, tableCase.ctx)).toEqual([]);
  });

  it('a lifted picture does not split the list its paragraph belongs to: it goes before the list', async () => {
    const item2 = `<w:p><w:pPr><w:numPr><w:ilvl w:val="0"/><w:numId w:val="2"/></w:numPr></w:pPr>${anchorPic('rId10')}<w:r><w:t>second</w:t></w:r></w:p>`;
    const r = await readData(await build({ body: li('first') + item2 + li('third'), ...STD }));
    expect(r.blocks.map(b => b.type)).toEqual(['resizableImage', 'orderedList']);
    expect(r.blocks[1].content).toHaveLength(3);
    expect(r.report.counts.list).toBe(1);
    expect(r.blocks[0].attrs!.anchorBlockId).toBe(blockIdOf(r.blocks[1].content![1].content![0]));
  });

  it('a body list and a table-cell list that share a numbering are flagged as complexNumbering (category 2), in either order', async () => {
    const before = await readData(await build({ body: li('body') + tbl(li('cell')), ...STD }));
    expect(before.report.counts.complexNumbering).toBe(1);
    const after = await readData(await build({ body: tbl(li('cell')) + li('body'), ...STD }));
    expect(after.report.counts.complexNumbering).toBe(1);
    for (const r of [before, after]) {
      const w = r.report.warnings.filter(x => x.feature === 'complexNumbering');
      expect(w).toHaveLength(1);
      expect(w[0].category).toBe(2);
      expect(w[0].message).toMatch(/table cell/i);
    }
    // a list in a cell and an unrelated body list are not
    const alone = await readData(await build({ body: tbl(li('cell')) + p('plain'), ...STD }));
    expect(alone.report.counts.complexNumbering).toBeUndefined();
  });

  it('a body list that resumes after a table keeps counting, and that is not reported as a table-cell continuation', async () => {
    const r = await readData(await build({ body: li('one') + li('two') + tbl(p('cell')) + li('three'), ...STD }));
    const lists = all(r.blocks, n => n.type === 'orderedList');
    expect(lists.map(l => l.attrs!.start)).toEqual([1, 3]);
    expect(r.report.warnings.filter(w => w.feature === 'complexNumbering').every(w => /interrupted/.test(w.message))).toBe(true);
  });

  it('a malformed numbering part is parsed, and warned about, once, however many containers have lists', async () => {
    const r = await readData(await build({ body: li('a') + tbl(li('b')) + tbl(li('c')), numbering: '<w:numbering', ...STD }));
    expect(r.report.warnings.filter(w => /numbering\.xml could not be read/.test(w.message))).toHaveLength(1);
    expect(r.ctx.numbering).toBeDefined();
  });
});

describe('sniffImageMime', () => {
  it('reads the real type from the bytes', () => {
    expect(sniffImageMime(PNG_1PX)).toBe('image/png');
    expect(sniffImageMime(Uint8Array.from([0xff, 0xd8, 0xff, 0xe0, 0, 0]))).toBe('image/jpeg');
    expect(sniffImageMime(new TextEncoder().encode('GIF89a....'))).toBe('image/gif');
    expect(sniffImageMime(SVG)).toBe('image/svg+xml');
    expect(sniffImageMime(EMF)).toBe('image/emf');
    expect(sniffImageMime(new Uint8Array(0))).toBeUndefined();
    expect(sniffImageMime(new TextEncoder().encode('<html><svg>'))).toBeUndefined();
  });
});
